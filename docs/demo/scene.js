// An annotation next to the thing it explains. The old one animates out first, then the new one animates in.
// target: a locator, or a { x, y, width, height } box. side: which side of the target the bubble sits on.
async function unsay() {
  await page.evaluate(async () => {
    const bubbles = [...document.querySelectorAll('.demo-say')]; if (!bubbles.length) return;
    bubbles.forEach(bubble => bubble.classList.remove('on'));
    await new Promise(resolve => setTimeout(resolve, 340)); bubbles.forEach(bubble => bubble.remove());
  });
}
async function say(target, text, side = 'left', dwell = 0) {
  await unsay();
  const box = typeof target.boundingBox === 'function' ? await target.boundingBox() : target;
  if (!box) return;
  await page.evaluate(([box, text, side]) => {
    const bubble = document.createElement('div'); bubble.className = 'demo-say'; bubble.dataset.side = side; bubble.textContent = text; document.body.append(bubble);
    const w = bubble.offsetWidth; const h = bubble.offsetHeight; const gap = 18;
    let left; let top;
    if (side === 'left') { left = box.x - w - gap; top = box.y + box.height / 2 - h / 2; }
    else if (side === 'right') { left = box.x + box.width + gap; top = box.y + box.height / 2 - h / 2; }
    else if (side === 'above') { left = box.x + box.width / 2 - w / 2; top = box.y - h - gap; }
    else { left = box.x + box.width / 2 - w / 2; top = box.y + box.height + gap; }
    bubble.style.left = `${Math.min(Math.max(12, left), innerWidth - w - 12)}px`; bubble.style.top = `${Math.min(Math.max(12, top), innerHeight - h - 12)}px`;
    bubble.getBoundingClientRect(); bubble.classList.add('on');
  }, [box, text, side]);
  if (dwell) await page.waitForTimeout(dwell);
}
// The box around an element's text (narrower than a block element), in page coordinates. Pass offset for text inside the iframe.
const textBox = async (locator, offset = { x: 0, y: 0 }) => {
  const box = await locator.evaluate(element => { const range = element.ownerDocument.createRange(); range.selectNodeContents(element); const rect = range.getBoundingClientRect(); return { x: rect.x, y: rect.y, width: rect.width, height: rect.height }; });
  return { x: box.x + offset.x, y: box.y + offset.y, width: box.width, height: box.height };
};
// A numbered concept tag. A new one slides the old one out first. instant: show without animating (after a document swap).
async function chapter(number, text, instant = false) {
  await page.evaluate(async ([number, text, instant]) => {
    const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
    let tag = document.getElementById('demo-chapter');
    if (!tag) { tag = document.createElement('div'); tag.id = 'demo-chapter'; document.body.append(tag); tag.getBoundingClientRect(); }
    else if (!instant && tag.classList.contains('on')) { tag.classList.remove('on'); await sleep(480); }
    const badge = document.createElement('b'); badge.textContent = number;
    const label = document.createElement('span'); label.textContent = text; tag.replaceChildren(badge, label);
    if (instant) tag.style.transition = 'none';
    tag.getBoundingClientRect(); tag.classList.add('on');
    if (instant) { tag.getBoundingClientRect(); tag.style.transition = ''; }
  }, [number, text, instant]);
}
