// Live demo, recorded as one continuous video. Two chapters: 01 comment on text, 02 the technical part:
// use it as a standalone file or in a hosted viewer.
//   1. browser-control execute 'await page.goto("http://127.0.0.1:4173/dist/demo.html")'     (a NEW session: no viewport override,
//      so the page fills the real window and the recording is full frame)
//   2. browser-control recording start <raw.mp4> --session <id> --mode cdp
//   3. browser-control execute --session <id> --file docs/demo/scene.js
//   4. browser-control recording stop --session <id>     then: python3 docs/demo/render.py <raw.mp4> docs
// With FRAMES set, skip steps 2 and 4 (no recording needed) and run render.py on the frames folder.
// Needs the dev server (npm run dev). Video palette: midnight ink and amber. The panes and documents keep their own colors.
//
// Continuity rules: no hard cuts. Cards, chapter tags and annotations all animate in and out. A document swap happens
// only under a curtain that is also built into the new document. Explanations appear next to the control they describe.
// Sharp capture: a background loop saves page screenshots (JPEGs) instead of using the soft CDP screencast.
// Set FRAMES to a folder to turn it on. render.py reads that folder. Leave it empty to use recording start/stop instead.
const FRAMES = '/private/var/folders/g1/nq659ng17qv8sp8nljtjpz380000gn/T/opencode/collabhtml-gif/frames';
const fs = FRAMES ? process.getBuiltinModule('node:fs') : null;
const stamps = []; let capturing = Boolean(FRAMES);
if (fs) { fs.rmSync(FRAMES, { recursive: true, force: true }); fs.mkdirSync(FRAMES, { recursive: true }); }
const captureLoop = (async () => {
  while (capturing) {
    try {
      const shot = await page.screenshot({ type: 'jpeg', quality: 92, scale: 'device' });
      fs.writeFileSync(`${FRAMES}/f${String(stamps.length).padStart(5, '0')}.jpg`, shot); stamps.push(Date.now());
    } catch { await new Promise(resolve => setTimeout(resolve, 30)); }
  }
})();
async function finishCapture() {
  if (!fs) return; capturing = false; await captureLoop;
  const lines = stamps.map((time, index) => `file 'f${String(index).padStart(5, '0')}.jpg'\nduration ${((stamps[index + 1] ?? time + 40) - time) / 1000}`);
  fs.writeFileSync(`${FRAMES}/frames.txt`, lines.join('\n') + '\n');
}

